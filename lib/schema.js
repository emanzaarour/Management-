export const headerKey = (value) =>
  String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
const aliases = {
  "Staff ID": ["ID", "Employee ID"],
  "Staff Name": ["Name", "Employee Name"],
  Position: ["Job Title"],
  Center: ["Centre"],
  Active: ["Is Active"],
  Email: ["User Email"],
  Name: ["User Name"],
  Type: ["Employee Type", "Staff Type"],
  "Default Start Time": ["Default Start"],
  "Default End Time": ["Default End"],
  Session: ["Session Number"],
  "Officer ID": ["OfficerID"],
};
export function headerIndex(headers, field) {
  const exact = headers.findIndex((h) => headerKey(h) === headerKey(field));
  if (exact >= 0) return exact;
  return headers.findIndex((h) =>
    (aliases[field] || []).some((a) => headerKey(h) === headerKey(a)),
  );
}
